export interface Balance {
  allowanceRemaining: number;
  allowanceTotal: number;
  topUpRemaining: number;
  topUpPacks: number;
}

const balanceDefault: Balance = {
  allowanceRemaining: 152,
  allowanceTotal: 300,
  topUpRemaining: 40,
  topUpPacks: 2,
};

export function getBalance(state: UsageState): Balance {
  if (state === 'lowBalance')
    return { allowanceRemaining: 48, allowanceTotal: 300, topUpRemaining: 40, topUpPacks: 2 };
  if (state === 'exhausted')
    return { allowanceRemaining: 0, allowanceTotal: 300, topUpRemaining: 0, topUpPacks: 0 };
  return balanceDefault;
}

